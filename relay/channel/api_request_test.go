func TestDoRequestRecordsUpstreamRequestID(t *testing.T) {
	service.InitHttpClient()
	tests := []struct {
		name      string
		oneapiID  string
		requestID string
		status    int
		wantID    string
	}{
		{name: "generic ID", requestID: "provider-request", status: http.StatusOK, wantID: "provider-request"},
		{name: "legacy ID", oneapiID: "gateway-request", status: http.StatusOK, wantID: "gateway-request"},
		{name: "legacy ID takes priority", oneapiID: "gateway-request", requestID: "provider-request", status: http.StatusOK, wantID: "gateway-request"},
		{name: "missing ID clears previous attempt", status: http.StatusOK},
		{name: "error response", requestID: "provider-error", status: http.StatusTooManyRequests, wantID: "provider-error"},
		{name: "long generic ID fits log column", requestID: strings.Repeat("x", 200), status: http.StatusOK, wantID: strings.Repeat("x", 128)},
	}
	for _, tt := range tests {
		for _, stream := range []bool{false, true} {
			name := tt.name + "/nonstream"
			if stream {
				name = tt.name + "/stream"
			}
			t.Run(name, func(t *testing.T) {
				upstream := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, _ *http.Request) {
					if tt.oneapiID != "" {
						w.Header().Set(common.RequestIdKey, tt.oneapiID)
					}
					if tt.requestID != "" {
						w.Header().Set("x-request-id", tt.requestID)
					}
					w.WriteHeader(tt.status)
					_, _ = io.WriteString(w, "upstream body")
				}))
				defer upstream.Close()
				ctx, _ := gin.CreateTestContext(httptest.NewRecorder())
				ctx.Request = httptest.NewRequest(http.MethodPost, "/v1/chat/completions", nil)
				ctx.Set(common.RequestIdKey, "local-request")
				ctx.Set(common.UpstreamRequestIdKey, "previous-attempt")
				req, err := http.NewRequest(http.MethodPost, upstream.URL, bytes.NewBufferString("request body"))
				require.NoError(t, err)
				info := &relaycommon.RelayInfo{IsStream: stream, DisablePing: true, ChannelMeta: &relaycommon.ChannelMeta{}}
				resp, err := DoRequest(ctx, req, info)
				require.NoError(t, err)
				defer resp.Body.Close()
				body, err := io.ReadAll(resp.Body)
				require.NoError(t, err)
				assert.Equal(t, tt.wantID, ctx.GetString(common.UpstreamRequestIdKey))
				assert.Equal(t, "local-request", ctx.GetString(common.RequestIdKey))
				assert.Equal(t, tt.status, resp.StatusCode)
				assert.Equal(t, tt.oneapiID, resp.Header.Get(common.RequestIdKey))
				assert.Equal(t, tt.requestID, resp.Header.Get("X-Request-Id"))
				assert.Equal(t, "upstream body", string(body))
			})
		}
	}

	t.Run("transport failure clears previous attempt", func(t *testing.T) {
		upstream := httptest.NewServer(http.HandlerFunc(func(http.ResponseWriter, *http.Request) {}))
		upstream.Close()
		ctx, _ := gin.CreateTestContext(httptest.NewRecorder())
		ctx.Request = httptest.NewRequest(http.MethodPost, "/v1/chat/completions", nil)
		ctx.Set(common.UpstreamRequestIdKey, "previous-attempt")
		req, err := http.NewRequest(http.MethodPost, upstream.URL, bytes.NewBufferString("request body"))
		require.NoError(t, err)
		resp, err := DoRequest(ctx, req, &relaycommon.RelayInfo{ChannelMeta: &relaycommon.ChannelMeta{}})
		require.Error(t, err)
		assert.Nil(t, resp)
		assert.Empty(t, ctx.GetString(common.UpstreamRequestIdKey))
	})
}

func TestNewTaskAPIRequestInheritsClientCancellation(t *testing.T) {
	recorder := httptest.NewRecorder()
	c, _ := gin.CreateTestContext(recorder)
	requestContext, cancel := context.WithCancel(context.Background())
	c.Request = httptest.NewRequest(http.MethodPost, "/v1/responses", nil).WithContext(requestContext)

	upstream, err := newTaskAPIRequest(c, "https://provider.example/tasks", nil)
	require.NoError(t, err)
	cancel()

	require.ErrorIs(t, upstream.Context().Err(), context.Canceled)
}

